def generate_virtualbox_script(params: dict):
    workers = params["workers"]
    base_ip = "192.168.56.10"  # IP base para master
    master_ip = base_ip
    worker_ips = [f"192.168.56.{11 + i}" for i in range(workers)]

    worker_clone_commands = ""
    for i in range(workers):
        worker_clone_commands += f"""
VBoxManage clonevm "ubuntu-k8s-template" --name "k8s-worker-{i+1}-auto" --register
VBoxManage modifyvm "k8s-worker-{i+1}-auto" --memory 2048 --cpus 2
VBoxManage modifyvm "k8s-worker-{i+1}-auto" --nic1 nat
VBoxManage modifyvm "k8s-worker-{i+1}-auto" --nic2 hostonly --hostonlyadapter2 "VirtualBox Host-Only Ethernet Adapter"
VBoxManage guestproperty set "k8s-worker-{i+1}-auto" /VirtualBox/GuestInfo/Net/0/V4/IP {worker_ips[i]}
VBoxManage startvm "k8s-worker-{i+1}-auto" --type headless
"""

    return f"""# Auto-generated VirtualBox provisioning script
# This script assumes an existing clean Ubuntu template VM named:
# ubuntu-k8s-template
#
# The template must already have:
# - Ubuntu installed
# - SSH enabled
# - user configured
# - no Kubernetes installed
# - VirtualBox Guest Additions installed for IP assignment

Write-Host "Creating Kubernetes master VM..."
VBoxManage clonevm "ubuntu-k8s-template" --name "k8s-master-auto" --register
VBoxManage modifyvm "k8s-master-auto" --memory 4096 --cpus 2
VBoxManage modifyvm "k8s-master-auto" --nic1 nat
VBoxManage modifyvm "k8s-master-auto" --nic2 hostonly --hostonlyadapter2 "VirtualBox Host-Only Ethernet Adapter"
VBoxManage guestproperty set "k8s-master-auto" /VirtualBox/GuestInfo/Net/0/V4/IP {master_ip}
VBoxManage startvm "k8s-master-auto" --type headless

Write-Host "Creating Kubernetes worker VMs..."
{worker_clone_commands}

Write-Host "VirtualBox VMs created and started."
Write-Host "Waiting 60 seconds for VMs to boot..."
Start-Sleep -Seconds 60
Write-Host "VMs should be ready. IPs assigned: Master={master_ip}, Workers={worker_ips}"
"""


def generate_inventory_json(params: dict):
    workers = params["workers"]
    master_ip = "192.168.56.10"
    worker_ips = [f"192.168.56.{11 + i}" for i in range(workers)]

    workers_list = [{"host": ip} for ip in worker_ips]

    inventory = {
        "ssh_user": "ubuntu",  # Asumiendo usuario ubuntu en las VMs
        "master": {"host": master_ip},
        "workers": workers_list,
    }

    return inventory


def generate_cluster_artifacts(params: dict):
    cluster_plan = generate_cluster_plan(params)
    master_script = generate_master_script(params)
    worker_script = generate_worker_script(params)
    virtualbox_script = ""
    inventory = {}

    return cluster_plan, master_script, worker_script, virtualbox_script, inventory
