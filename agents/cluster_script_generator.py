"""
Genera scripts de instalación de Kubernetes.

Incluye:
- Setup del master
- Setup de workers
- Configuración de containerd y kubeadm

Scripts seguros y deterministas.
"""


def generate_cluster_plan(params: dict):
    masters = params["masters"]
    workers = params["workers"]
    cni = params["cni"]
    version = params["kubernetes_version"]
    runtime = params["container_runtime"]

    return f"""
Plan para desplegar un clúster Kubernetes desde cero:

1. Preparar infraestructura base:
   - {masters} nodo(s) master/control-plane
   - {workers} nodo(s) worker
   - Máquinas Linux Ubuntu ya provisionadas por el cloud system
   - Conectividad y SSH funcionales entre nodos

2. Instalar dependencias en todos los nodos:
   - {runtime}
   - kubeadm
   - kubelet
   - kubectl
   - versión Kubernetes: {version}

3. Inicializar el nodo master:
   - ejecutar kubeadm init
   - configurar kubeconfig
   - instalar plugin CNI: {cni}

4. Unir los workers:
   - ejecutar kubeadm join en cada worker usando el token generado por el master

5. Validar el clúster:
   - kubectl get nodes
   - kubectl get pods -A
"""


def generate_master_script(params: dict):
    cni = params["cni"]
    version = params["kubernetes_version"]

    if cni == "flannel":
        cni_command = "kubectl apply -f https://github.com/flannel-io/flannel/releases/latest/download/kube-flannel.yml"
        pod_cidr = "10.244.0.0/16"
    else:
        cni_command = "kubectl apply -f https://raw.githubusercontent.com/projectcalico/calico/v3.30.3/manifests/calico.yaml"
        pod_cidr = "192.168.0.0/16"

    return f"""#!/bin/bash

set -e

echo "[MASTER] Installing dependencies..."
sudo apt update
sudo apt install -y apt-transport-https ca-certificates curl gpg containerd

echo "[MASTER] Configuring containerd..."
sudo mkdir -p /etc/containerd
containerd config default | sudo tee /etc/containerd/config.toml >/dev/null
sudo sed -i 's/SystemdCgroup = false/SystemdCgroup = true/' /etc/containerd/config.toml
sudo systemctl restart containerd
sudo systemctl enable containerd

echo "[MASTER] Disabling swap..."
sudo swapoff -a
sudo sed -i '/ swap / s/^/#/' /etc/fstab

echo "[MASTER] Installing Kubernetes components ({version})..."
sudo mkdir -p -m 755 /etc/apt/keyrings
curl -fsSL https://pkgs.k8s.io/core:/stable:/{version}/deb/Release.key | sudo gpg --dearmor -o /etc/apt/keyrings/kubernetes-apt-keyring.gpg

echo 'deb [signed-by=/etc/apt/keyrings/kubernetes-apt-keyring.gpg] https://pkgs.k8s.io/core:/stable:/{version}/deb/ /' | sudo tee /etc/apt/sources.list.d/kubernetes.list

sudo apt update
sudo apt install -y kubelet kubeadm kubectl
sudo apt-mark hold kubelet kubeadm kubectl

echo "[MASTER] Initializing Kubernetes cluster..."
sudo kubeadm init --pod-network-cidr={pod_cidr}

echo "[MASTER] Configuring kubeconfig..."
mkdir -p $HOME/.kube
sudo cp -f /etc/kubernetes/admin.conf $HOME/.kube/config
sudo chown $(id -u):$(id -g) $HOME/.kube/config

echo "[MASTER] Installing CNI: {cni}"
{cni_command}

echo "[MASTER] Join command for workers:"
kubeadm token create --print-join-command
"""


